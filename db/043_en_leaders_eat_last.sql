There's a test that runs through the whole book and that Sinek never states as such. Try to formulate it yourself before you see what it is.

## Rebuild before you look

**One.** What is the test? Hint: it has to do with when you look at an organisation.

:::Show the answer
**What the organisation does when things get hard.** Good days don't set anyone apart. What's informative is how the cost gets shared when there's a downturn, a cut, a crisis.
:::

**Two.** Sinek contrasts two ways of responding to a downturn. What are they, and what do people remember about each?

:::Show the answer
**Sharing the pain among everyone, including whoever is in charge, or tightening the belt the fast way, on the people at the bottom.** The book's point isn't that laying people off is wrong in itself. It's that the way an organisation shares the cost is the most honest information it gives about itself, and everyone reads it, especially the people who stay.
:::

**Three.** Brought down to your scale, which isn't that of a factory: in what small situations does the same test show up?

:::Show the answer
When someone has to work a weekend and it's decided who goes. When a decision from above lands badly and you either defend it as your own or hand it over as someone else's. When something good gets handed out, like a visible project or recognition. They are small versions of the same test, and the team notices every one of them.
:::

Nobody remembers the speech at the annual meeting. Everyone remembers what happened the time it got hard.

## What has aged

**The examples of companies that save themselves by sharing the pain.** They are chosen stories: you hear about what went well, not about the companies that did the same thing and went under anyway. Take them as an illustration of an idea, not as proof that it always works. The test is about what signal people receive, not about whether the company survives.

**What it doesn't say.** The book doesn't give you a recipe for deciding how much pain to share and how. You have to work that out yourself with the real conditions of your institution; the book only warns you that people will watch how you do it.

## For now

Remember the last time something got truly complicated in your area. Write in one line what your team learned about you that day. If you don't like what you wrote, you have material for next time.
