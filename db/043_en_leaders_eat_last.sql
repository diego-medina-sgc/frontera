Sinek devotes a good part of the book to how the circle of safety breaks, and almost none of it has to do with bad bosses. His central idea here:

**The conditions that destroy trust appear on their own, through the inertia of the structure. If you do nothing to prevent them, they happen anyway.**

There are four, and it helps to keep them separate because they look different.

- **Distance.** The further the decision-maker is from the person receiving the decision, the easier it is to make decisions that hurt, not out of cruelty but because from far away people become numbers.
- **Abundance badly shared.** When whoever is at the top receives first and more, the signal is that risk isn't shared.
- **Numbers above people.** The metric stops being an indicator and becomes the goal.
- **Chronic instability.** Reorganisations, rules that change, priorities that flip. From below it isn't read as dynamism, it's read as danger.

## One case, two of the four at once

Hypothetical, to see how they work together. The leadership of a school measures the admissions team by **number of interviews held per week**. It's a reasonable metric: it reflects activity, and it's easy to measure.

Over time the predictable happens. Interviews get shorter to fit more in the calendar, families who almost certainly won't enrol get scheduled, informal chats get counted. The number goes up. The conversation with each family, which was what mattered, gets worse. Nobody decides to do this: each person does the reasonable thing to look good against the metric.

That is the third factor in its pure state. And it combines with the first: whoever looks at the dashboard doesn't hear the interviews, so the number looks like good news.

Sinek's lesson isn't "don't measure". It's that **a metric with no contact with the reality it measures ends up rewarding the wrong thing**, and that the distance between whoever looks at the number and whoever does the work is what makes it possible.

## Where the idea doesn't apply

**Not every change is instability.** A necessary reorganisation, explained in time and with what is settled and what isn't, doesn't break the circle. What breaks it is change without explanation, or permanent change.

**Not every number is an enemy.** Measuring is necessary. The problem appears when the number replaces judgement instead of supporting it.

**Not everything is the structure's fault.** Sinek insists that these are conditions that appear on their own, but also that someone has to take charge of correcting them. "It's the structure" doesn't work as an excuse.

## Test your understanding

Classify each situation into one of the four conditions (distance, abundance badly shared, numbers above people, instability) **before** opening the answer.

1. The leadership announces a change in the hours for attending to families without having talked to the people who do it, who find out through an email.
2. In three months, the department changed its main goal four times, and each time it was asked to "prioritise this" over the previous one.
3. The person who closed the most enquiries in the month gets rewarded, and enquiries start being closed without being resolved.

:::Show the answer
**1 is distance, 2 is instability, 3 is numbers above people.**

**Number 1 is distance** because the decision-maker didn't have the people affected in front of them. The change doesn't even need to be bad: the way it was communicated already conveys that the people who do the work aren't counted as part of the decision.

**Number 2 is instability** because each change, taken separately, may be defensible. The problem is the pattern: people learn that nothing they do today will count tomorrow, and the reasonable response is not to commit fully.

**Number 3 is the metric turned into the goal.** What's being measured is "closing enquiries", what matters is "resolving them", and people optimise the first because it's what gets rewarded.
:::

