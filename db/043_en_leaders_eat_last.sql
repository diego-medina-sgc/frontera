If you're going to use this book to decide how you lead, it helps to know where it's weak. The idea of this piece:

**What holds up in the book is what Sinek observes about how people behave in organisations. What holds up less is the explanation he puts on top of it.**

There are three problems.

- **The biology.** Sinek explains almost everything with four substances, which he arranges in two pairs: endorphins and dopamine, those of individual achievement; serotonin and oxytocin, those of bonding. He adds cortisol as the stress one. It's tidy and memorable, but it's a simplification that neuroscience doesn't support: none of those substances does just one thing or works like a lever you raise or lower.
- **The idealisation of the military.** The Marines as a model of a healthy organisation illustrate the idea, but a school or a marketing department doesn't resemble a combat unit in what's at stake or in the incentives.
- **What's missing: demand.** The book talks a lot about protecting and little about demanding.

## Worked case: separating what holds up from what doesn't

A critical-reading exercise. Take this sentence, which sums up a type of claim that is common in the book: "your team performs better because the oxytocin released by trust makes it collaborate".

It can be split in two:

1. **Observation:** in teams where there is trust, people collaborate more and hide mistakes less.
2. **Explanation:** that happens because of one particular substance.

The first you can check in your own team, by looking at what happens when someone makes a mistake. The second you can check neither with your experience nor, as the book presents it, with the research. And you don't need to: the decision you make (how you react to a mistake) is the same with or without the chemistry.

The method works for the whole book: separate what is observed from what is explained. You work with the first. The second you take as a metaphor that helps you remember.

## Where the criticism doesn't apply

**It doesn't invalidate the central idea.** That the biological explanation is inflated doesn't mean the circle of safety is false. The observation that people protect themselves when they feel in danger is solid and is backed by other research, such as Amy Edmondson's on psychological safety.

**It doesn't make the book useless.** Its value lies in the images and in the focus on the leader's responsibility, not in the chemistry.

## Test your understanding

Classify each statement as an **observation** (you can verify it by looking at your team) or an **explanation** (it would need evidence you don't have) **before** opening the answer.

1. "When the boss shares the credit by name, people report problems sooner."
2. "Trust is generated because the brain releases a specific substance when someone follows through."
3. "When a mistake is reported late, it tends to cost more."

:::Show the answer
**1 is an observation, 2 is an explanation, 3 is an observation.**

**Numbers 1 and 3** describe behaviours you can see: what people do and how much it costs. You can test them on your team for a month and keep whatever you see.

**Number 2** makes a claim about mechanisms in the body, and that is precisely the part that neuroscience doesn't support as the book lays it out. Even if it were true, it wouldn't change what you do on Monday. When an explanation doesn't change any decision, you don't need to believe it in order to use the book.
:::

## What to do this week

When someone quotes this book to you (or when you quote it yourself), ask the exercise's question: is this something observed in real teams, or an explanation of why? With the first, test it in your area. The second, use as an image, not as an argument.
