An exercise, not a summary. It takes twenty minutes and you only do it once a quarter. Before you start, a question to force you to recall what you read.

## Retrieval before applying

Answer before you open it: according to Sinek, what makes someone "inside" the circle in practice? Is it what the org chart says?

:::Show the answer
**No. It's what makes the person feel safe enough to tell you about a problem.** The org chart says who reports to whom; the circle is defined by trust and by the cost the person in charge is willing to take on. That's why the real edge almost never matches the formal one, and it's the one you'll draw in step one.
:::

## The exercise

**One. Draw the real edge.** Write down the names of your team. Next to each one, answer honestly: if this person makes a serious mistake tomorrow, will they tell me first or try to fix it on their own? The ones who would try to fix it alone are outside the circle, even if they're inside the org chart.

**Two. Find the last time you absorbed a blow.** A specific moment when you could have pointed at someone on your team and didn't, whether upward or outward. If you can't find one in the last three months, there are two possible explanations: nothing bad happened, or the circle isn't as solid as you think.

**Three. Choose the axis you're missing.** Using Edmondson's model: is your team closer to the comfort zone (comfortable, not much demanded) or the anxiety zone (demanded, covering themselves)? What you need to raise depends on which one it is, and raising the wrong one makes things worse.

**Four, the only one with consequences:** pick one conversation this week where you will do something different because of this. One. Write down which one and with whom.

## One more round to test step three

Imagine that in step one you found that three out of five people would fix the mistake on their own. Which axis would you raise first, and what would you do?

:::Show the answer
**Safety first.** If people fix things on their own so they don't have to tell you, the signal is that telling you is costly. Raising demand at that point would add pressure to a team that is already covering itself, and you'd end up in the anxiety zone.

In concrete terms: the next time someone tells you about a mistake, respond with "what do you need from me?" before any judgement, and say out loud a recent mistake of your own. Once people reliably tell you early, that's when you raise the demand.
:::

The rest is airport philosophy.
