The book is more inspiring than practical. This piece turns its ideas into behaviours you can do on a Monday, and starts from a single one:

**When you lead, your team reads the moments when protecting someone costs you, and from that decides how much to guard against you.**

The behaviours that follow from it:

- **Absorb the blow.** When something goes wrong and explanations have to be given upward, you give them.
- **Give credit by name.** Who did what, said in front of the people who matter.
- **Protect whoever brings the bad news.** Your reaction to the first one decides whether there will be a second.
- **Shorten the distance on purpose.** Go and see, don't wait for the report.
- **Say what is settled and what isn't.** Unexplained uncertainty is what triggers defence mode.

## Worked case: the version that goes up and the version that comes down

Hypothetical. A school sends a mass mailing to families that goes wrong: a wrong date for a meeting. The coordinator has to report to the leadership. Two possible versions of the same message.

**Version A:** "There was a mistake in the mailing. The person who prepared it entered the wrong date."

**Version B:** "There was a mistake in the mailing: the date went out wrong. The final check is mine, and I didn't do it carefully. We've already sent the correction and I've added a double-check step."

Both are true. The difference is what the team learns when they find out which one was sent. With A, they learn that the risk of mistakes is individual and that whoever makes one is left alone. With B, they learn that reporting early is safe. The first produces a team that hides mistakes; the second, one that reports them while they're still cheap.

And notice what B has besides protection: it has a correction. Absorbing the blow isn't whining or making excuses; it's taking responsibility and changing something.

## Where the idea doesn't apply

**Absorbing isn't hiding.** If a problem is one of sustained performance, taking responsibility upward solves nothing: you have to talk to the person, face to face. Protecting isn't covering up.

**Not every mistake is yours.** Some mistakes belong to one person and you have to talk to them about it. What you don't do is point at them in public or upward as the explanation.

**Giving credit isn't inflating.** If you say "great work" about everything, the signal gets diluted. Credit by name is worth something because it's specific.

## Test your understanding

Decide what you would do in each case **before** opening the answer.

1. Someone on the team tells you they've been stuck for two days on a problem they don't know how to solve, and that it will probably affect a deadline. You're in a hurry and in a bad mood.
2. A project went very well and you're congratulated in front of the leadership. Three people did the work.
3. A reorganisation is coming and you still don't know how it will affect you or your team.

:::Show the answer
**1.** Stop for a minute, even if you're in a hurry, and respond with a question, not a reproach: "thanks for telling me, what do you need from me?". Your reaction to the first piece of bad news decides whether the next one reaches you in time or when it's already expensive. The bad mood you can talk about later, if needed.

**2.** Hand the credit back right there, with names: "X, Y and Z did this, and here is what each one did". It takes ten seconds and it's exactly the moment the team is watching. If you let it pass, the signal is that merit goes up and risk goes down.

**3.** Say what you know and what you don't: "there's a reorganisation, I don't yet know how it affects us, I'll tell you as soon as I do". Unexplained ambiguity is what triggers defence. You don't need to lie that everything is fine; they need to know what is settled and what isn't.
:::

