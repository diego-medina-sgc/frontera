Almost everyone keeps the title and the image of the circle from Sinek's book. What fades with time is the hard part, which is the part that's useful. Before reading anything, rebuild it yourself.

## Rebuild before you look

Answer each one out loud or in writing. Then open the answer and compare.

**One.** What defines the edge of the circle of safety: who is inside or who is left outside?

:::Show the answer
**Who is left outside.** It's not an abstract value, it's an edge. Sinek insists that as an organisation grows, it multiplies the edges: every department, every layer, every "them" draws a smaller circle. If you answered "who is inside", you kept the image and lost the mechanism.
:::

**Two.** A team protects itself from the team next door, within the same institution. How does that feel from the inside, and what does it indicate?

:::Show the answer
**It feels like loyalty, and it's the symptom that the larger circle has broken.** Protecting your own team from the one next door looks like a virtue, and in this framework it's a sign that the organisation has stopped being a single circle.
:::

**Three.** Why are decisions that hurt people made more easily when the decision-maker is far away? Is it because of malice?

:::Show the answer
**It's not malice, it's distance.** From far away, people turn into numbers, and a cut in a spreadsheet is just a line. Three metres away, it's someone with a name. That's why Sinek proposes shortening the distance on purpose: the organisation lengthens it by itself.
:::

**Four.** According to the book, when is a leader's integrity measured?

:::Show the answer
**When protecting someone costs them dearly.** Gestures on good days don't define the circle. What counts is what you do when it costs you.
:::

If you got three or four, the book still stands in your head. If you got one, it's no big deal: that's normal for a book read years ago, and this piece is for exactly that.

## What you probably remember wrong

**That the book proposes being soft.** It doesn't. It proposes absorbing the risk for your people, which is quite a bit more demanding than being nice.

## What has aged

**The chemical explanation.** The substances Sinek uses to explain behaviour (the achievement pair and the bonding pair) organise the presentation well but are a simplification that neuroscience doesn't support. What he observes about behaviour still holds; the chemistry, take it as a metaphor.

**The silence about demand.** The book protects a lot and demands little. Later research on psychological safety is explicit: safety and high standards together.

## For now

Think about your team and ask yourself where the edge is today. Who is inside and who, without anyone having decided it, ended up outside. Write down one name.
